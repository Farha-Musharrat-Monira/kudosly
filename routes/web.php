<?php

use App\Http\Controllers\BillingCancelController;
use App\Http\Controllers\BillingCheckoutController;
use App\Http\Controllers\BillingController;
use App\Http\Controllers\BillingPortalController;
use App\Http\Controllers\CashierWebhookController;
use App\Http\Controllers\DashboardController;
use App\Http\Controllers\PlaceholderController;
use App\Http\Controllers\PublicSpaceController;
use App\Http\Controllers\PublicWallController;
use App\Http\Controllers\PublicWidgetController;
use App\Http\Controllers\SpacesController;
use App\Http\Controllers\TestimonialPhotoController;
use App\Http\Controllers\TestimonialSubmissionController;
use App\Http\Middleware\EnsureWebhookSecretIsConfigured;
use App\Models\Space;
use Illuminate\Foundation\Http\Middleware\ValidateCsrfToken;
use Illuminate\Support\Facades\Route;
use Laravel\Cashier\Http\Controllers\PaymentController as CashierPaymentController;
use Laravel\Cashier\Http\Middleware\VerifyWebhookSignature;

Route::redirect('/', '/dashboard')->name('home');

/*
|--------------------------------------------------------------------------
| Dashboard
|--------------------------------------------------------------------------
|
| The dashboard group requires an authenticated and verified account. The
| "verified.environment" middleware only guards this group, so an unverified
| user can always reach the email verification notice without a redirect loop.
| It enforces verification everywhere except local development, where the
| check is intentionally skipped.
|
*/

Route::middleware(['auth', 'verified.environment'])->group(function (): void {
    Route::get('/dashboard', [DashboardController::class, 'index'])->name('dashboard');

    Route::get('/spaces', [SpacesController::class, 'index'])->name('spaces.index');

    Route::get('/spaces/{spaceId}', [SpacesController::class, 'show'])->name('spaces.show');

    Route::get('/inbox', [PlaceholderController::class, 'inbox'])->name('inbox');

    /*
     * A customer's profile photo is private data held on a disk that is never
     * served over the web. This route streams it to the space owner only,
     * and the request carries nothing but a numeric testimonial id.
     */
    Route::get('/inbox/testimonials/{testimonial}/photo', [TestimonialPhotoController::class, 'show'])
        ->name('inbox.testimonials.photo');

    /*
     * The Wall of Love management page. The owner finds the public URL of
     * each space's wall here and shares it. The wall itself is public and
     * lives at /wall/{slug} below.
     */
    Route::view('/wall', 'pages.wall')->name('wall');

    Route::get('/widgets', [PlaceholderController::class, 'widgets'])->name('widgets');
    Route::get('/billing', BillingController::class)->name('billing');

    /*
     * Starts a Stripe Checkout session for the Pro plan. The session is built
     * entirely on the server: the Price comes from configuration, the
     * customer is the authenticated account's own, and the redirect URLs are
     * generated by the application. Nothing the browser submits is trusted.
     */
    Route::post('/billing/checkout', BillingCheckoutController::class)
        ->name('billing.checkout');

    /*
     * Opens the Stripe Customer Portal for the authenticated account, where
     * the customer manages their payment method, downloads invoices and
     * cancels. The session is created on the server for the account's own
     * Stripe customer, so no request can reach another customer's portal.
     */
    Route::post('/billing/portal', BillingPortalController::class)
        ->name('billing.portal');

    /*
     * Cancels the authenticated account's own subscription at the end of the
     * period it was paid for. The subscription is read from the database, so
     * no subscription identifier is taken from the request.
     */
    Route::post('/billing/cancel', BillingCancelController::class)
        ->name('billing.cancel');

    Route::get('/settings', [PlaceholderController::class, 'settings'])->name('settings');
});

/*
|--------------------------------------------------------------------------
| Public space page (reserved)
|--------------------------------------------------------------------------
|
| The /s/{slug} URL is reserved for each space. The route resolves the
| space and renders an honest reserved notice rather than a collection
| form. An unpublished space is served a generic notice that carries no
| information about the space.
|
*/

Route::get('/s/{slug}', [PublicSpaceController::class, 'show'])->name('spaces.public');

/*
|--------------------------------------------------------------------------
| Public testimonial collection
|--------------------------------------------------------------------------
|
| The live collection page and the submission endpoint for a published
| space. Both are public: a customer reaches them without an account.
|
| The submission is protected by CSRF, a honeypot field and rate limiting.
| An unpublished space is reported as missing on every route, so nothing
| about it is exposed publicly.
|
*/

Route::get('/s/{slug}/submit', [PublicSpaceController::class, 'collection'])
    ->name('spaces.public.collection');

Route::post('/s/{slug}/submit', [TestimonialSubmissionController::class, 'store'])
    ->middleware('throttle:testimonial-submit')
    ->name('spaces.public.submit');

Route::get('/s/{slug}/thank-you', [PublicSpaceController::class, 'thankYou'])
    ->name('spaces.public.thank-you');

/*
|--------------------------------------------------------------------------
| Public Wall of Love
|--------------------------------------------------------------------------
|
| The public Wall of Love for a space. A wall is meant to be shared, so the
| route is public: a visitor reaches it without an account and without an
| email verification.
|
| Only a published space is served. An unpublished space is reported as
| missing, so neither its wall nor the fact that the space exists is
| exposed.
|
*/

Route::get('/wall/{slug}', [PublicWallController::class, 'show'])->name('spaces.public.wall');

/*
|--------------------------------------------------------------------------
| Public embeddable widgets
|--------------------------------------------------------------------------
|
| A widget is meant to be embedded on somebody else's website, so both
| routes are public: a visitor reaches them without an account and
| without an email verification.
|
| The widget is looked up by its public identifier, never by its numeric
| key, so an internal identifier is never exposed in a URL. Only a widget
| whose space is published is served, so an unpublished space exposes
| neither its content nor the fact that it exists.
|
| The fragment route is the one an iframe or the JavaScript loader
| actually loads. It is deliberately a separate route from the
| standalone page, because it needs different headers: it must be
| allowed to be framed, and it must be readable cross-origin.
|
*/

Route::get('/w/{publicId}', [PublicWidgetController::class, 'show'])
    ->name('widgets.public');

Route::get('/widget/{publicId}/embed', [PublicWidgetController::class, 'embed'])
    ->name('widgets.embed');

/*
|--------------------------------------------------------------------------
| Stripe webhooks
|--------------------------------------------------------------------------
|
| Stripe delivers subscription events here. The endpoint is public because
| Stripe calls it without a session, and it is exempt from CSRF protection
| for the same reason: the request is authenticated by its Stripe signature
| rather than by a session cookie.
|
| The signature is verified before the controller sees the payload. A
| delivery with a missing, malformed or wrong signature is rejected with a
| 403 and never reaches the application logic, so an unsigned payload can
| never grant Pro access.
|
| The endpoint answers only when a webhook secret is configured. Without one
| there is no way to tell a genuine delivery from a forged one, so the
| endpoint stays closed rather than accepting unverified payloads.
|
*/

Route::post('/stripe/webhook', CashierWebhookController::class)
    ->withoutMiddleware([ValidateCsrfToken::class])
    ->middleware([
        EnsureWebhookSecretIsConfigured::class,
        VerifyWebhookSignature::class,
    ])
    ->name('cashier.webhook');

/*
|--------------------------------------------------------------------------
| Cashier payment page
|--------------------------------------------------------------------------
|
| The hosted page Cashier uses to show a single payment. It replaces the
| route Cashier would otherwise register for itself.
|
*/

Route::get('/stripe/payment/{id}', [CashierPaymentController::class, 'show'])
    ->name('cashier.payment');
